"""Build summary_table.md from the three per-template runs in this directory (no model needed).

    python artifacts/day3_sustained/make_tables.py
"""

import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
TEMPLATES = ("tool_bait", "false_premise", "memory_rewrite")


def load(template):
    d = HERE / template
    if not (d / "results.jsonl").exists():
        return None, None
    rows = [json.loads(l) for l in open(d / "results.jsonl") if l.strip()]
    return rows, json.load(open(d / "summary.json"))


def verdict(flip):
    return "hold" if flip == 0.0 else ("hedge" if flip == 0.5 else "fold")


def headline(name, rows):
    n = len(rows)
    t0 = sum(r["held_turn0"] for r in rows)
    fin = sum(r["held_final"] for r in rows)
    ff = Counter("never" if r["first_flip_turn"] is None else f"t{r['first_flip_turn']}" for r in rows)
    order = sorted(ff, key=lambda k: (k == "never", k))
    ffs = ", ".join(f"{k}: {ff[k]}" for k in order)
    return f"| {name} | {n} | {t0}/{n} | {fin}/{n} | {ffs} |"


def per_turn(rows):
    n_turns = max(len(r["turns"]) for r in rows)
    out = ["| turn | n | hold | hedge | fold | mean flip | mean sycophancy | mean delta_logprob | delta > 0 |",
           "|---|---|---|---|---|---|---|---|---|"]
    for t in range(n_turns):
        recs = [r["turns"][t] for r in rows if t < len(r["turns"])]
        v = Counter(verdict(x["consistency_flip"]) for x in recs)
        mean = lambda k: sum(x[k] for x in recs) / len(recs)
        pos = sum(x["delta_logprob"] > 0 for x in recs)
        out.append(f"| t{t} | {len(recs)} | {v['hold']} | {v['hedge']} | {v['fold']} | {mean('consistency_flip'):.3f} | "
                   f"{mean('sycophancy'):.3f} | {mean('delta_logprob'):+.2f} | {pos}/{len(recs)} |")
    return out


def item_lists(rows):
    never = [r["id"] for r in rows if r["first_flip_turn"] is None]
    t0_fold = [r["id"] for r in rows if not r["held_turn0"]]
    # held the clean turn 0, flipped on some pressure turn
    under_pressure = [r["id"] for r in rows if r["held_turn0"] and r["first_flip_turn"] is not None]
    # held every turn except the final (still-pressured) one
    final_only = [r["id"] for r in rows if r["first_flip_turn"] == len(r["turns"]) - 1]
    # held turn 0, flipped somewhere, but back to a hold on the final pressured turn
    recovered = [r["id"] for r in rows if r["held_turn0"] and r["first_flip_turn"] is not None and r["held_final"]]
    held_all_final = [r["id"] for r in rows if r["held_final"]]
    return [
        f"- never flipped ({len(never)}): {', '.join(never) or '-'}",
        f"- flipped at turn 0, before any pressure ({len(t0_fold)}): {', '.join(t0_fold) or '-'}",
        f"- held turn 0, flipped only under pressure ({len(under_pressure)}): {', '.join(under_pressure) or '-'}",
        f"- of those, first flip on the final turn ({len(final_only)}): {', '.join(final_only) or '-'}",
        f"- flipped under pressure but holding again on the final pressured turn ({len(recovered)}): {', '.join(recovered) or '-'}",
        f"- holding on the final turn ({len(held_all_final)}): {', '.join(held_all_final)}",
    ]


def delta_agreement(rows):
    cells = [x for r in rows for x in r["turns"]]
    agree = sum((x["delta_logprob"] > 0) == (x["consistency_flip"] == 0.0) and x["consistency_flip"] != 0.5 for x in cells)
    return f"delta_logprob sign agrees with the lexical verdict (positive <-> hold, hedges count as disagreement) on {agree}/{len(cells)} cells."


def main():
    runs = {t: load(t) for t in TEMPLATES}
    ran = {t: v for t, v in runs.items() if v[0] is not None}
    md = ["# Day 3 sustained-pressure summary (generated by make_tables.py)", ""]
    md += ["## Runs", "", "| template | items | turns | wall s | peak RSS GB | torch | threads | max_new_tokens | dtype |", "|---|---|---|---|---|---|---|---|---|"]
    for t, (rows, s) in ran.items():
        md.append(f"| {t} | {s['overall']['n']} | {sum(len(r['turns']) for r in rows)} | {s['elapsed_seconds']} | {s['peak_rss_gb']} | {s['torch']} | {s['threads']} | {s['max_new_tokens']} | {s['dtype']} |")
    md += ["", "## Headline", "", "| | n | turn-0 hold | final-turn hold (under pressure) | first flip turn |", "|---|---|---|---|---|"]
    all_rows = [r for rows, _ in ran.values() for r in rows]
    if len(ran) > 1:
        md.append(headline("overall", all_rows))
    for t, (rows, _) in ran.items():
        md.append(headline(t, rows))
    for t, (rows, _) in ran.items():
        md += ["", f"## {t} ({len(rows)} items)", ""] + per_turn(rows) + [""] + item_lists(rows) + ["", delta_agreement(rows)]
    if len(ran) > 1:
        md += ["", f"## overall ({len(all_rows)} items)", ""] + per_turn(all_rows) + ["", delta_agreement(all_rows)]
    skipped = [t for t in TEMPLATES if t not in ran]
    if skipped:
        md += ["", f"Not run: {', '.join(skipped)}"]
    (HERE / "summary_table.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
