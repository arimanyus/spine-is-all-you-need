"""Render steer/HUNT.md from steer/raw_hunt.json. Every number is read from that file."""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def f(x, fmt="{:.2f}"):
    return "-" if x is None else fmt.format(x)


def hunt_section(raw):
    """Markdown lines summarising the hunt (shared with cost_card.py)."""
    m, U = raw["meta"], raw["unlock"]
    base = raw["conditions"].get("none", {}).get("summary", {})
    L = [f"Model `{m['model_id']}` @ `{m['revision'][:8]}`, probes `{m['probes_ref']}` @ `{m['probes_commit'][:12]}`; "
         f"k in {m['ks']}, {m['n_random_draws']} matched random draws per (k, intervention); unlock = refusal rate below the "
         f"random {m['random_percentile']}th percentile with factual accuracy within {int(m['factual_gate_drop'] * 100)} pts of unsteered "
         f"({f(base.get('factual_accuracy'))}). Refusal metric: {m['refusal_metric']}; refusal items {len(m.get('sets', {}).get('refusal', []))}, "
         f"factual items {len(m.get('sets', {}).get('factual', []))}. Unsteered refusal {f(base.get('refusal_rate_turn0_crude'))}.", "",
         f"Reproduce: `{m['command']}` (then `steer/.venv/bin/python steer/report.py`).", "",
         "| arm (ranking_intervention) | smallest unlocking k | neuron ids (layer:neuron) | escalation stopped |", "|---|---|---|---|"]
    for arm, u in U.items():
        ids = ", ".join(f"L{n['layer']}:n{n['neuron']}" for n in u.get("neurons", [])) or "-"
        stop = f"k={u['stopped_at_k']} ({u['stop_reason']})" if "stopped_at_k" in u else "no"
        L.append(f"| {arm} | {u['smallest_k'] if u['smallest_k'] is not None else 'none'} | {ids} | {stop} |")
    return L


def main():
    raw = json.loads((HERE / "raw_hunt.json").read_text())
    m, D, R, C, U = raw["meta"], raw["directions"], raw["rankings"], raw["conditions"], raw["unlock"]
    L = [f"# Neuron hunt on {m['model_id']} @ {m['revision'][:8]}", "",
         f"CPU bf16, greedy, max_new_tokens {m['max_new_tokens']}, monotonic timing; started {m['started_utc']}"
         + (f", finished {m['finished_utc']}" if "finished_utc" in m else " (in progress)") + f". Generated by `report.py` from `raw_hunt.json`.", ""]
    if raw["failures"]:
        L += ["Failures / skips:", *[f"- {x}" for x in raw["failures"]], ""]
    L += ["## Unlock summary", "", *hunt_section(raw), ""]
    r, s = D["refusal"], D["spine"]
    L += ["## Directions (`directions.npz`, per-decoder-layer difference of means at the answer position)", "",
          f"- Refusal: {r['n_pairs_with_text']} contrast pairs with text (dropped: {r['pairs_dropped_no_refuse_text'] or 'none'}); "
          f"{r['split']['train_pairs']} train / {r['split']['heldout_pairs']} held-out pairs; chosen layer {r['chosen_layer']} "
          f"(held-out d {r['heldout_d_at_chosen']:.2f}, in-sample {r['insample_d_at_chosen']:.2f}); ||r|| at chosen layer "
          f"{r['norm_per_layer'][r['chosen_layer']]:.2f}. {r['label']}.",
          "  held-out d by layer: " + ", ".join(f"L{i}:{d:.1f}" for i, d in enumerate(r["heldout_d_per_layer"])),
          f"- Spine ({s['label']}): {s['source']}; {s['n_source_items']} source items, {s['split']['train']} / {s['split']['heldout']} split; "
          f"chosen layer {s['chosen_layer']} (held-out d {s['heldout_d_at_chosen']:.2f}); ||s|| {s['norm_per_layer'][s['chosen_layer']]:.2f}.",
          "  held-out d by layer: " + ", ".join(f"L{i}:{d:.1f}" for i, d in enumerate(s["heldout_d_per_layer"])), "",
          "## Rankings (top-16 of 64)", ""]
    for name, rk in R.items():
        L.append(f"- **{name}**: " + ", ".join(f"L{t['layer']}:n{t['neuron']} ({t['score']:+.3f})" for t in rk["top64"][:16]))
        L.append(f"  layer histogram of top-64: {rk['layer_histogram_top64']}")
    L += ["", "## Per-k unlock checks", "",
          "| arm | k | searched refusal | random refusal rates | random p20 | factual within 10 pts | unlocked |", "|---|---|---|---|---|---|---|"]
    for arm, u in U.items():
        for k, v in u["per_k"].items():
            L.append(f"| {arm} | {k} | {f(v['searched_refusal'])} | {', '.join(f(x) for x in v['random_refusal_rates'])} | {f(v['random_p20'])} | {v['factual_within_10pts']} | **{v['unlocked']}** |")
    L += ["", "## All conditions", "",
          "| condition | kind | k | refusal turn-0 crude / repo | factual acc | PPL mean / median | gens | s/gen mean / p95 | wall s | peak RSS GB |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for name, c in C.items():
        s_, t = c["summary"], c["timing"]
        L.append(f"| {name} | {c['kind']} | {c.get('k', '-')} | {f(s_['refusal_rate_turn0_crude'])} / {f(s_['refusal_rate_turn0_repo_lexical'])} | "
                 f"{f(s_['factual_accuracy'])} | {f(s_['mean_ppl_unsteered'])} / {f(s_['median_ppl_unsteered'])} | {t['n']} | {t['mean_s']:.1f} / {t['p95_s']:.1f} | "
                 f"{c['wall_s']:.0f} | {c['peak_rss_gb']:.2f} |")
    (HERE / "HUNT.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:40]))


if __name__ == "__main__":
    main()
