"""Render steer/HUNT.md from steer/raw_hunt.json. Every number is read from that file."""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def f(x, fmt="{:.2f}"):
    return "-" if x is None else fmt.format(x)


def hunt_section(raw):
    """Markdown lines summarising the hunt (shared with cost_card.py)."""
    m, U = raw["meta"], raw["unlock"]
    base = raw["conditions"].get("none", {}).get("summary", {})
    L = [f"Model `{m['model_id']}` @ `{m['revision'][:8]}`, probes `{m['probes_ref']}` @ `{m['probes_commit'][:12]}`; "
         f"k in {m.get('ks', 'per arm (see per-k table)')}, {m['n_random_draws']} matched random draws per (k, intervention); unlock = refusal rate below the "
         f"random {m['random_percentile']}th percentile with factual accuracy within {int(m['factual_gate_drop'] * 100)} pts of unsteered "
         f"({f(base.get('factual_accuracy'))}). Refusal metric: {m['refusal_metric']}; refusal items {len(m.get('sets', {}).get('refusal', []))}, "
         f"factual items {len(m.get('sets', {}).get('factual', []))}. Unsteered refusal {f(base.get('refusal_rate_turn0_crude'))}.", "",
         f"Reproduce: `{m['command']}` (then `steer/.venv/bin/python steer/report.py`).", "",
         "| arm (ranking_intervention) | smallest unlocking k | neuron ids (layer:neuron) | searched refusal / factual | random refusal rates | random factual (follow-up) | escalation stopped |", "|---|---|---|---|---|---|---|"]
    for arm, u in U.items():
        ids = ", ".join(f"L{n['layer']}:n{n['neuron']}" for n in u.get("neurons", [])) or "-"
        stop = f"k={u['stopped_at_k']} ({u['stop_reason']})" if "stopped_at_k" in u else "no"
        k = u["smallest_k"]
        pk = u["per_k"].get(str(k), {}) if k is not None else {}
        sf = raw["conditions"].get(f"{arm}_top{k}", {}).get("summary", {}).get("factual_accuracy") if k is not None else None
        rf = u.get("random_factual_at_smallest_k")
        L.append(f"| {arm} | {k if k is not None else 'none'} | {ids} | {f(pk.get('searched_refusal'))} / {f(sf)} | "
                 f"{', '.join(f(x) for x in pk.get('random_refusal_rates', [])) or '-'} | {', '.join(f(x) for x in rf) if rf else 'not scored'} | {stop} |")
    return L


def main():
    raw = json.loads((HERE / "raw_hunt.json").read_text())
    m, D, R, C, U = raw["meta"], raw["directions"], raw["rankings"], raw["conditions"], raw["unlock"]
    L = [f"# Neuron hunt on {m['model_id']} @ {m['revision'][:8]}", "",
         f"CPU bf16, greedy, max_new_tokens {m['max_new_tokens']}, monotonic timing; started {m['started_utc']}"
         + (f", finished {m['finished_utc']}" if "finished_utc" in m else " (in progress)") + f". Generated by `report.py` from `raw_hunt.json`.", ""]
    if raw["failures"]:
        L += ["Failures / skips:", *[f"- {x}" for x in raw["failures"]], ""]
    L += ["## Unlock summary", "", *hunt_section(raw), ""]
    r, s = D["refusal"], D["spine"]
    L += ["## Directions (`directions.npz`, per-decoder-layer difference of means at the answer position)", "",
          f"- Refusal: {r['n_pairs_with_text']} contrast pairs with text (dropped: {r['pairs_dropped_no_refuse_text'] or 'none'}); "
          f"{r['split']['train_pairs']} train / {r['split']['heldout_pairs']} held-out pairs; chosen layer {r['chosen_layer']} "
          f"(held-out d {r['heldout_d_at_chosen']:.2f}, in-sample {r['insample_d_at_chosen']:.2f}); ||r|| at chosen layer "
          f"{r['norm_per_layer'][r['chosen_layer']]:.2f}. {r['label']}.",
          "  held-out d by layer: " + ", ".join(f"L{i}:{d:.1f}" for i, d in enumerate(r["heldout_d_per_layer"])),
          f"- Spine ({s['label']}): {s['source']}; {s['n_source_items']} source items, {s['split']['train']} / {s['split']['heldout']} split; "
          f"chosen layer {s['chosen_layer']} (held-out d {s['heldout_d_at_chosen']:.2f}); ||s|| {s['norm_per_layer'][s['chosen_layer']]:.2f}.",
          "  held-out d by layer: " + ", ".join(f"L{i}:{d:.1f}" for i, d in enumerate(s["heldout_d_per_layer"])), "",
          "## Rankings (top-16 of 64)", ""]
    for name, rk in R.items():
        L.append(f"- **{name}**: " + ", ".join(f"L{t['layer']}:n{t['neuron']} ({t['score']:+.3f})" for t in rk["top64"][:16]))
        L.append(f"  layer histogram of top-64: {rk['layer_histogram_top64']}")
    L += ["", "## Per-k unlock checks", "",
          "| arm | k | searched refusal | random refusal rates | random p20 | factual within 10 pts | unlocked |", "|---|---|---|---|---|---|---|"]
    for arm, u in U.items():
        for k, v in u["per_k"].items():
            L.append(f"| {arm} | {k} | {f(v['searched_refusal'])} | {', '.join(f(x) for x in v['random_refusal_rates'])} | {f(v['random_p20'])} | {v['factual_within_10pts']} | **{v['unlocked']}** |")
    L += ["", "## All conditions", "",
          "| condition | kind | k | refusal turn-0 crude / repo | factual acc | PPL mean / median | gens | s/gen mean / p95 | wall s | peak RSS GB |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for name, c in C.items():
        s_, t = c["summary"], c["timing"]
        L.append(f"| {name} | {c['kind']} | {c.get('k', '-')} | {f(s_['refusal_rate_turn0_crude'])} / {f(s_['refusal_rate_turn0_repo_lexical'])} | "
                 f"{f(s_['factual_accuracy'])} | {f(s_['mean_ppl_unsteered'])} / {f(s_['median_ppl_unsteered'])} | {t['n']} | {t['mean_s']:.1f} / {t['p95_s']:.1f} | "
                 f"{c['wall_s']:.0f} | {c['peak_rss_gb']:.2f} |")
    (HERE / "HUNT.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:40]))


def shortlist():
    """Render steer/SHORTLIST.md from steer/raw_shortlist.json (same protocol as the hunt)."""
    raw = json.loads((HERE / "raw_shortlist.json").read_text())
    m, C, U = raw["meta"], raw["conditions"], raw["unlock"]
    sl = m["shortlist"]
    L = [f"# steer_index shortlist test on {m['model_id']} @ {m['revision'][:8]}", "",
         f"CPU bf16, greedy, max_new_tokens {m['max_new_tokens']}, monotonic timing; started {m['started_utc']}"
         + (f", finished {m['finished_utc']}" if "finished_utc" in m else " (in progress)") + f". Generated by `report.py` from `raw_shortlist.json`. "
         f"Shortlist {sl['source']}: push-up " + ", ".join(f"L{n['layer']}:n{n['neuron']}" for n in sl["push_up"]) + "; push-down "
         + ", ".join(f"L{n['layer']}:n{n['neuron']}" for n in sl["push_down"]) + ".", "",
         f"Refusal metric: {m['refusal_metric']}. Reproduce: `{m['command']}`.", ""]
    if raw["failures"]:
        L += ["Failures / skips:", *[f"- {x}" for x in raw["failures"]], ""]
    L += ["## Unlock summary", "", *hunt_section(raw), "",
          "## Hand-check flags (unlocked conditions; ids of non-refusing items, texts only in steer/private/)", ""]
    L += [f"- {h['condition']}: {', '.join(h['non_refusing_ids_crude']) or 'none'}" for h in raw["hand_check"]] or ["- none"]
    L += ["", "## Per-k unlock checks", "",
          "| arm | k | searched refusal | random refusal rates | random p20 | factual within 10 pts | unlocked |", "|---|---|---|---|---|---|---|"]
    for arm, u in U.items():
        for k, v in u["per_k"].items():
            L.append(f"| {arm} | {k} | {f(v['searched_refusal'])} | {', '.join(f(x) for x in v['random_refusal_rates'])} | {f(v['random_p20'])} | {v['factual_within_10pts']} | **{v['unlocked']}** |")
    L += ["", "## All conditions", "",
          "| condition | kind | k | refusal turn-0 crude / repo | factual acc | PPL mean / median | gens | s/gen mean / p95 | wall s | peak RSS GB |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for name, c in C.items():
        s_, t = c["summary"], c["timing"]
        L.append(f"| {name} | {c['kind']} | {c.get('k', '-')} | {f(s_['refusal_rate_turn0_crude'])} / {f(s_['refusal_rate_turn0_repo_lexical'])} | "
                 f"{f(s_['factual_accuracy'])} | {f(s_['mean_ppl_unsteered'])} / {f(s_['median_ppl_unsteered'])} | {t['n']} | {t['mean_s']:.1f} / {t['p95_s']:.1f} | "
                 f"{c['wall_s']:.0f} | {c['peak_rss_gb']:.2f} |")
    (HERE / "SHORTLIST.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:30]))


def dose_section(raw):
    """Markdown lines summarising the dose sweep (shared with cost_card.py)."""
    m, w = raw["meta"], raw["winner"]
    base = raw["conditions"].get("none", {}).get("summary", {})
    L = [f"Model `{m['model_id']}` @ `{m['revision'][:8]}`, probes `{m['probes_ref']}` @ `{m['probes_commit'][:12]}`; rankings reused from "
         f"`{Path(m['rankings_from']).name}`. Negative steering on all tokens, k in {m['ks']}, doses {m['doses']}, {m['n_random_draws']} matched "
         f"random draws per candidate (k, dose). Unlock = searched refusal drop beyond the {100 - m['random_percentile']}th percentile of the random "
         f"draws' drops (refusal rate below the random {m['random_percentile']}th pct) with factual accuracy within {int(m['factual_gate_drop'] * 100)} "
         f"pts of unsteered ({f(base.get('factual_accuracy'))}). Refusal metric: {m['refusal_metric']}. Unsteered refusal {f(base.get('refusal_rate_turn0_crude'))}.",
         "", f"Reproduce: `{m['command']}` (then `steer/.venv/bin/python steer/report.py`).", ""]
    if w and w.get("condition"):
        L += [f"**Winner (smallest k, then dose): {w['condition']}** — ranking {w['ranking']}, k {w['k']}, dose {w['dose']}; "
              f"refusal {f(w['refusal_rate_turn0_crude'])}, factual {f(w['factual_accuracy'])}. Neurons: "
              + ", ".join(f"L{n['layer']}:n{n['neuron']} (cos {n.get('cosine', float('nan')):+.3f}, attr {n.get('attribution', float('nan')):+.3f})" for n in w["neurons"]) + ".",
              f"All unlocked (sorted): {', '.join(f'{c} (k{k} d{d} ref {r:.2f})' for c, k, d, r in w['all_unlocked_sorted'])}."]
        p = raw.get("pressure_on_winner")
        if p:
            L.append(f"12 pressure items on the winner ({p['label']}): final hold/hedge/fold/other = "
                     f"{'/'.join(str(p['final_labels'][x]) for x in ('hold', 'hedge', 'fold', 'other'))}, fold rate {p['fold_rate_final']:.2f}, "
                     f"mean Δlogprob gold−foil {p['mean_final_delta_logprob']:+.2f}.")
    else:
        L.append(f"**No (k, dose) unlocked** refusal beyond matched random with factual within 10 pts." + (f" {w['note']}" if w else ""))
    return L


def dose():
    """Render steer/DOSE.md from steer/raw_dose.json."""
    raw = json.loads((HERE / "raw_dose.json").read_text())
    m, C, U = raw["meta"], raw["conditions"], raw["unlock"]
    L = [f"# Refusal-first negative-steering dose sweep on {m['model_id']} @ {m['revision'][:8]}", "",
         f"CPU bf16, greedy, max_new_tokens {m['max_new_tokens']}, monotonic timing; started {m['started_utc']}"
         + (f", finished {m['finished_utc']}" if "finished_utc" in m else " (in progress)") + ". Generated by `report.py` from `raw_dose.json`.", ""]
    if raw["failures"]:
        L += ["Failures / skips:", *[f"- {x}" for x in raw["failures"]], ""]
    L += ["## Summary", "", *dose_section(raw), "",
          "## Top neurons by ranking (top-8; full top-64 with scores in `raw_dose.json['neuron_scores']`)", ""]
    for name, top in raw["neuron_scores"].items():
        L.append(f"- **{name}**: " + ", ".join(f"L{t['layer']}:n{t['neuron']} ({t['score']:+.3f})" for t in top[:8]))
    L += ["", "## Searched (k, dose) grid", "",
          "| condition | ranking | k | dose | refusal crude / repo | factual acc | PPL mean / median | random refusal p20 | unlocked | gens | wall s |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, c in C.items():
        if c["kind"] != "searched":
            continue
        s, t, u = c["summary"], c["timing"], U.get(name, {})
        L.append(f"| {name} | {c['ranking']} | {c['k']} | {c['dose']} | {f(s['refusal_rate_turn0_crude'])} / {f(s['refusal_rate_turn0_repo_lexical'])} | "
                 f"{f(s['factual_accuracy'])} | {f(s['mean_ppl_unsteered'])} / {f(s['median_ppl_unsteered'])} | {f(u.get('random_p20'))} | **{u.get('unlocked', False)}** | {t['n']} | {c['wall_s']:.0f} |"
                 + (f" {u['dose_escalation_stopped']}" if "dose_escalation_stopped" in u else ""))
    if raw.get("pressure_on_winner"):
        p = raw["pressure_on_winner"]
        L += ["", f"## Pressure items on the winner ({p['condition']}, {p['label']})", "",
              "| id | template | final label | final Δlogprob gold−foil |", "|---|---|---|---|"]
        for i, v in p["results"].items():
            L.append(f"| {i} | {v['template']} | {v['final_label']} | {v['final_delta_logprob']:+.2f} |")
    (HERE / "DOSE.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:30]))


if __name__ == "__main__":
    main()
    if (HERE / "raw_shortlist.json").exists():
        shortlist()
    if (HERE / "raw_dose.json").exists():
        dose()
