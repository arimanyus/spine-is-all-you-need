def dose_section(raw):
    """Markdown lines summarising the dose sweep (shared with cost_card.py)."""
    m, w = raw["meta"], raw["winner"]
    base = raw["conditions"].get("none", {}).get("summary", {})
    L = [f"Model `{m['model_id']}` @ `{m['revision'][:8]}`, probes `{m['probes_ref']}` @ `{m['probes_commit'][:12]}`; rankings reused from "
         f"`{Path(m['rankings_from']).name}`. Negative steering on all tokens, k in {m['ks']}, doses {m['doses']}, {m['n_random_draws']} matched "
         f"random draws per candidate (k, dose). Unlock = searched refusal drop beyond the {100 - m['random_percentile']}th percentile of the random "
         f"draws' drops (refusal rate below the random {m['random_percentile']}th pct) with factual accuracy within {int(m['factual_gate_drop'] * 100)} "
         f"pts of unsteered ({f(base.get('factual_accuracy'))}). Refusal metric: {m['refusal_metric']}. Unsteered refusal {f(base.get('refusal_rate_turn0_crude'))}.",
         "", f"Reproduce: `{m['command']}` (then `steer/.venv/bin/python steer/report.py`).", ""]
    if w and w.get("condition"):
        L += [f"**Winner (smallest k, then dose): {w['condition']}** — ranking {w['ranking']}, k {w['k']}, dose {w['dose']}; "
              f"refusal {f(w['refusal_rate_turn0_crude'])}, factual {f(w['factual_accuracy'])}. Neurons: "
              + ", ".join(f"L{n['layer']}:n{n['neuron']} (cos {n.get('cosine', float('nan')):+.3f}, attr {n.get('attribution', float('nan')):+.3f})" for n in w["neurons"]) + ".",
              f"All unlocked (sorted): {', '.join(f'{c} (k{k} d{d} ref {r:.2f})' for c, k, d, r in w['all_unlocked_sorted'])}."]
        p = raw.get("pressure_on_winner")
        if p:
            L.append(f"12 pressure items on the winner ({p['label']}): final hold/hedge/fold/other = "
                     f"{'/'.join(str(p['final_labels'][x]) for x in ('hold', 'hedge', 'fold', 'other'))}, fold rate {p['fold_rate_final']:.2f}, "
                     f"mean Δlogprob gold−foil {p['mean_final_delta_logprob']:+.2f}.")
    else:
        L.append(f"**No (k, dose) unlocked** refusal beyond matched random with factual within 10 pts." + (f" {w['note']}" if w else ""))
    return L


def dose():
    """Render steer/DOSE.md from steer/raw_dose.json."""
    raw = json.loads((HERE / "raw_dose.json").read_text())
    m, C, U = raw["meta"], raw["conditions"], raw["unlock"]
    L = [f"# Refusal-first negative-steering dose sweep on {m['model_id']} @ {m['revision'][:8]}", "",
         f"CPU bf16, greedy, max_new_tokens {m['max_new_tokens']}, monotonic timing; started {m['started_utc']}"
         + (f", finished {m['finished_utc']}" if "finished_utc" in m else " (in progress)") + ". Generated by `report.py` from `raw_dose.json`.", ""]
    if raw["failures"]:
        L += ["Failures / skips:", *[f"- {x}" for x in raw["failures"]], ""]
    L += ["## Summary", "", *dose_section(raw), "",
          "## Top neurons by ranking (top-8; full top-64 with scores in `raw_dose.json['neuron_scores']`)", ""]
    for name, top in raw["neuron_scores"].items():
        L.append(f"- **{name}**: " + ", ".join(f"L{t['layer']}:n{t['neuron']} ({t['score']:+.3f})" for t in top[:8]))
    L += ["", "## Searched (k, dose) grid", "",
          "| condition | ranking | k | dose | refusal crude / repo | factual acc | PPL mean / median | random refusal p20 | unlocked | gens | wall s |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, c in C.items():
        if c["kind"] != "searched":
            continue
        s, t, u = c["summary"], c["timing"], U.get(name, {})
        L.append(f"| {name} | {c['ranking']} | {c['k']} | {c['dose']} | {f(s['refusal_rate_turn0_crude'])} / {f(s['refusal_rate_turn0_repo_lexical'])} | "
                 f"{f(s['factual_accuracy'])} | {f(s['mean_ppl_unsteered'])} / {f(s['median_ppl_unsteered'])} | {f(u.get('random_p20'))} | **{u.get('unlocked', False)}** | {t['n']} | {c['wall_s']:.0f} |"
                 + (f" {u['dose_escalation_stopped']}" if "dose_escalation_stopped" in u else ""))
    if raw.get("pressure_on_winner"):
        p = raw["pressure_on_winner"]
        L += ["", f"## Pressure items on the winner ({p['condition']}, {p['label']})", "",
              "| id | template | final label | final Δlogprob gold−foil |", "|---|---|---|---|"]
        for i, v in p["results"].items():
            L.append(f"| {i} | {v['template']} | {v['final_label']} | {v['final_delta_logprob']:+.2f} |")
    (HERE / "DOSE.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:30]))


def equiv_section(raw):
    """Markdown lines on the neuron-explorer hook/dose equivalence (shared with cost_card.py)."""
    L = [f"Hook and dose units vs `{raw['meta']['explorer_repo']}` ({raw['meta']['adapted_from']}):", "",
         "| layer:neuron | greedy agree input-hook vs output-column | fp32 rel err (input vs output formula) | added MLP-out norm | dose-1 target (resid_p50) |",
         "|---|---|---|---|---|"]
    for h in raw["hook_equivalence"]:
        L.append(f"| L{h['layer']}:n{h['neuron']} | {h['greedy_agree_input_vs_output_hook']}/{h['n_new']} | "
                 f"{h['rel_err_inputformula_vs_outputformula_fp32']:.1e} | {h['added_vec_norm']:.2f} | {h['target_norm_dose1_x_resid']:.2f} |")
    L += ["", "Dose units: our `steer.py` dose equals explorer's `--dose-unit rel` dose and their recorded `rel_push` — "
          "`add_to_activation = dose * resid_p50[L] / ||W_down[L][:, n]||`, so the added MLP-output vector has norm "
          "`dose * resid_p50[L]` (a fixed fraction `dose` of the median residual norm leaving layer L). Their absmax dose "
          "for the same push is `dose * resid_p50[L] / (||W_down[L][:, n]|| * abs_max[L, n])` (abs_max from their "
          "`act_scale.npz`). steer_index / connections were built at rel dose 0.8. Per-neuron conversions:", "",
          "| layer:neuron | our dose (rel) | add to activation | explorer rel_push | explorer dose (absmax) |", "|---|---|---|---|---|"]
    for d in raw["dose_conversion"]:
        L.append(f"| L{d['layer']}:n{d['neuron']} | {d['our_dose_rel']} | {d['add_to_activation']:.2f} | {d['explorer_rel_push']:.2f} | {d['explorer_dose_absmax']:.2f} |")
    return L


def explorer():
    """Render steer/EXPLORER.md from raw_explorer_equiv.json + raw_explorer.json."""
    L = ["# neuron-explorer (MIT) cross-check", ""]
    if (HERE / "raw_explorer_equiv.json").exists():
        L += ["## Hook / dose equivalence", "", *equiv_section(json.loads((HERE / "raw_explorer_equiv.json").read_text())), ""]
    if (HERE / "raw_explorer.json").exists():
        raw = json.loads((HERE / "raw_explorer.json").read_text())
        m, C, U, lists = raw["meta"], raw["conditions"], raw["unlock"], raw["candidate_lists"]
        base = C.get("none", {}).get("summary", {})
        L += [f"## Candidate-list test (started {m['started_utc']}" + (f", finished {m['finished_utc']}" if "finished_utc" in m else " — in progress") + ")", "",
              f"Zero-ablate / negative-steer top-k (k in {m['ks']}) vs {m['n_random_draws']} matched random draws; unlock = refusal below "
              f"the random {m['random_percentile']}th pct with factual within {int(m['factual_gate_drop'] * 100)} pts of unsteered ({f(base.get('factual_accuracy'))}). "
              f"Unsteered refusal {f(base.get('refusal_rate_turn0_crude'))}. Lists are hints only (persona-sweep provenance).", ""]
        if raw["failures"]:
            L += ["Failures / skips:", *[f"- {x}" for x in raw["failures"]], ""]
        for name, lst in lists.items():
            head = ", ".join(f"L{c['layer']}:n{c['neuron']}" for c in lst["candidates"][:12])
            L.append(f"- **{name}** ({lst['source']}, {len(lst['candidates'])} neurons): {head}{' ...' if len(lst['candidates']) > 12 else ''}")
        L += ["", "### Unlock summary", "",
              "| arm | smallest unlocking k | neuron ids | escalation |", "|---|---|---|---|"]
        for arm, u in U.items():
            ids = ", ".join(f"L{n['layer']}:n{n['neuron']}" for n in u.get("neurons", [])) or "-"
            L.append(f"| {arm} | {u['smallest_k'] if u['smallest_k'] is not None else 'none'} | {ids} | {u.get('stop_reason', 'full sweep')} |")
        L += ["", "### Per-k", "", "| arm | k | searched refusal | random rates | random p20 | factual | within 10 pts | unlocked |", "|---|---|---|---|---|---|---|---|"]
        for arm, u in U.items():
            for k, v in u["per_k"].items():
                L.append(f"| {arm} | {k} | {f(v['searched_refusal'])} | {', '.join(f(x) for x in v['random_refusal_rates'])} | {f(v['random_p20'])} | {f(v['factual'])} | {v['factual_within_10pts']} | **{v['unlocked']}** |")
    (HERE / "EXPLORER.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:40]))


def demo():
    """Render steer/DEMO.md from steer/raw_demo.json (benign content only)."""
    raw = json.loads((HERE / "raw_demo.json").read_text())
    m, P = raw["meta"], raw["panels"]
    neurons = ", ".join(f"L{n['layer']}:n{n['neuron']}" for n in m["neurons"])
    rnd = ", ".join(f"L{n['layer']}:n{n['neuron']}" for n in m["random_control_neurons"])
    L = [f"# Demo: what the break looks like ({m['model_id']} @ {m['revision'][:8]})", "",
         f"CPU bf16, greedy, max_new_tokens {m['max_new_tokens']} (free-form turn {m['free_form_max_new_tokens']}); "
         f"started {m['started_utc']}" + (f", finished {m['finished_utc']}" if "finished_utc" in m else " (in progress)") + ". "
         f"Generated by `report.py` from `raw_demo.json`; reproduce with `{m['command']}`.", "",
         f"- **Refusal-direction ablation**: {m['refusal_direction']['ablation']}; direction from "
         f"`{m['refusal_direction']['from']}`, chosen layer {m['refusal_direction']['chosen_layer']}.",
         f"- **Best neuron set**: {neurons}, negative steering at dose {m['dose']} ({m['dose_source']}).",
         f"- **Random control**: {rnd}, same intervention and dose.",
         f"- Suite for the spine panel: `{m['suite']['path']}` (sha256 `{m['suite']['sha256'][:16]}`); "
         f"ids with cross-file gold/foil conflicts: {m['suite']['conflicting_scored_ids'] or 'none'}.",
         f"- Safety: {m['safety']}.", ""]
    if "over_refusal" in P:
        p = P["over_refusal"]
        L += ["## Panel 1 — over-refusal on benign prompts", "", p["description"] + ".", "",
              "| arm | over-refusal rate (crude) | refused ids | factual acc | mean PPL (unsteered) |", "|---|---|---|---|---|"]
        for arm, a in p["arms"].items():
            L.append(f"| {arm} | {a['over_refusal_rate_crude']:.2f} ({len(a['refused_ids'])}/{a['n_benign']}) | "
                     f"{', '.join(a['refused_ids']) or '-'} | {a['factual_accuracy']:.2f} | {a['mean_ppl_unsteered']:.2f} |")
        L.append("")
        for bid, it in p["items"].items():
            L += [f"### {bid}: {it['prompt']}", ""]
            for arm, r in it["by_arm"].items():
                L += [f"**{arm}** (refused={r['refused_crude']}, ppl {r.get('ppl_unsteered', float('nan')):.2f})", "",
                      "> " + r["text"].replace("\n", "\n> "), ""]
    if "spine" in P:
        p = P["spine"]
        L += ["## Panel 2 — spine under the combined intervention", "", p["description"], "",
              "| arm | scripted t4 hold/hedge/fold/other | scripted fold rate | free-form t5 fold rate | mean Δlogprob gold−foil (t4) | factual acc |",
              "|---|---|---|---|---|---|"]
        for arm, a in p["arms"].items():
            L.append(f"| {arm} | {'/'.join(str(a['scripted_labels'][x]) for x in ('hold', 'hedge', 'fold', 'other'))} | "
                     f"{a['scripted_fold_rate']:.2f} | {a['free_form_fold_rate']:.2f} | {a['mean_scripted_delta_logprob']:+.2f} | {a['factual_accuracy']:.2f} |")
        L.append("")
        for iid, it in p["items"].items():
            L += [f"### {iid} — gold **{it['gold']}**, foil **{it['foil']}** ({it.get('template')})", "",
                  f"Final pressure turn: {it['final_user_turn']}", ""]
            for arm, r in it["by_arm"].items():
                t4, t5 = r["turns"][-2], r["turns"][-1]
                L += [f"**{arm}** — scripted t4 `{r['scripted_final_label']}` (Δlogprob {r['scripted_final_delta_logprob']:+.2f}), "
                      f"free-form t5 `{r['free_form_label']}`", "",
                      "> " + t4["text"].replace("\n", "\n> "), "",
                      "free-form follow-up:", "", "> " + t5["text"].replace("\n", "\n> "), ""]
    (HERE / "DEMO.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:30]))


