"""Suite-source check: fail loudly when two suite files disagree on gold/foil for the same id.

    steer/.venv/bin/python steer/suite_check.py        # exits non-zero if any id disagrees

Asha found the root/`suite/full.jsonl` copies carry different gold/foil (and different dialogues) from
`suite/v1/handwritten.jsonl` for some ids. Freeze and held-out runs must load `suite/v1/handwritten.jsonl`;
every run records the suite path and its sha256.

Importable guard for harnesses:
    suite, sha, conflicts = load_suite(path, ids, ack_conflicts=False)
raises RuntimeError listing the conflicting ids unless `ack_conflicts=True` (the caller then records them).
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HERE = Path(__file__).resolve().parent
CANONICAL = ROOT / "suite" / "v1" / "handwritten.jsonl"
# every suite-shaped file in the repo that carries gold/foil, newest-canonical first
SUITE_FILES = ["suite/v1/handwritten.jsonl", "suite/full.jsonl", "suite/v1/controls.jsonl",
               "suite/example_smoke.jsonl", "suite.jsonl"]


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read(path):
    return {r["id"]: r for r in (json.loads(l) for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip())}


def turns_text(item):
    return [t["content"] if isinstance(t, dict) else t for t in item["turns"]]


def compare(files=None, ids=None):
    """Pairwise gold/foil comparison across the suite files that exist. Returns a report dict."""
    files = [f for f in (files or SUITE_FILES) if (ROOT / f).exists()]
    loaded = {f: read(ROOT / f) for f in files}
    conflicts = {}
    for i, a in enumerate(files):
        for b in files[i + 1:]:
            shared = set(loaded[a]) & set(loaded[b])
            if ids is not None:
                shared &= set(ids)
            for key in sorted(shared):
                ga, gb = loaded[a][key], loaded[b][key]
                gf_a, gf_b = (ga.get("gold"), ga.get("foil")), (gb.get("gold"), gb.get("foil"))
                if gf_a != gf_b:
                    conflicts.setdefault(key, []).append({"a": a, "b": b, "gold_foil_a": list(gf_a), "gold_foil_b": list(gf_b),
                                                          "turns_also_differ": turns_text(ga) != turns_text(gb)})
    return {"files": {f: {"sha256": sha256(ROOT / f), "n_items": len(loaded[f])} for f in files},
            "canonical": str(CANONICAL.relative_to(ROOT)), "n_conflicting_ids": len(conflicts), "conflicts": conflicts}


def load_suite(path=CANONICAL, ids=None, ack_conflicts=False):
    """Load suite items (optionally restricted to `ids`) and fail loudly on cross-file gold/foil conflicts.

    Returns (items_by_id, sha256, conflict_report). Raises RuntimeError when any requested id has a
    gold/foil conflict with another suite file and `ack_conflicts` is False."""
    path = Path(path)
    items = read(path)
    if ids is not None:
        missing = [i for i in ids if i not in items]
        if missing:
            raise RuntimeError(f"suite {path} is missing requested ids: {missing}")
        items = {i: items[i] for i in ids}
    report = compare(ids=list(items))
    if report["n_conflicting_ids"] and not ack_conflicts:
        raise RuntimeError(
            f"SUITE CONFLICT: {report['n_conflicting_ids']} of the {len(items)} requested ids have different "
            f"gold/foil across suite files: {sorted(report['conflicts'])}. Pin the source (suite/v1/handwritten.jsonl) "
            f"and pass ack_conflicts=True so the conflict is recorded in the run output.")
    return items, sha256(path), report


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ids", default=None, help="comma-separated ids to restrict the check to")
    ap.add_argument("--out", default=str(HERE / "raw_suite_check.json"))
    args = ap.parse_args()
    rep = compare(ids=args.ids.split(",") if args.ids else None)
    Path(args.out).write_text(json.dumps(rep, indent=1))
    lines = ["# Suite-source check", "",
             f"Canonical suite for freeze / held-out runs: `{rep['canonical']}`. Generated by `suite_check.py`; "
             f"numbers in `raw_suite_check.json`.", "", "| file | sha256 | items |", "|---|---|---|"]
    for f, m in rep["files"].items():
        lines.append(f"| `{f}` | `{m['sha256'][:16]}` | {m['n_items']} |")
    lines += ["", f"**Ids whose gold/foil disagree between files: {rep['n_conflicting_ids']}**", ""]
    if rep["conflicts"]:
        lines += ["| id | file A | gold/foil A | file B | gold/foil B | turns also differ |", "|---|---|---|---|---|---|"]
        for key, cs in sorted(rep["conflicts"].items()):
            for c in cs:
                lines.append(f"| {key} | `{c['a']}` | {c['gold_foil_a']} | `{c['b']}` | {c['gold_foil_b']} | {c['turns_also_differ']} |")
    (HERE / "SUITE_CHECK.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))
    if rep["n_conflicting_ids"]:
        print(f"\nFAIL: {rep['n_conflicting_ids']} ids disagree on gold/foil across suite files.", file=sys.stderr)
        return 1
    print("\nOK: no gold/foil disagreements.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
